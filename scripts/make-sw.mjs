// Service worker, generated after `vite build`: writes dist/sw.js with the exact list of built
// files and a cache name derived from a hash of their paths and contents, so any change to any
// file makes a new cache (and a byte-different sw.js, which is what makes the browser update).
//
// Behaviour: precache everything on install; cache-first for same-origin GETs with a network
// fallback; navigations get the cached index.html; old skitch caches are deleted on activate;
// the waiting worker only takes over when the page posts 'skipWaiting' (the RELOAD control on the
// "new version" ticket). All URLs are relative to the worker, so dist/ works from any path.
//   node scripts/make-sw.mjs [distDir]
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const SW_FILE = 'sw.js';
export const CACHE_PREFIX = 'skitch-';

/** Every file under `dir` as a sorted list of '/'-separated relative paths, sw.js excluded. */
export function listFiles(dir) {
  const out = [];
  const walk = (d) => {
    for (const name of readdirSync(d)) {
      const p = join(d, name);
      if (statSync(p).isDirectory()) walk(p);
      else out.push(relative(dir, p).split(sep).join('/'));
    }
  };
  walk(dir);
  return out.filter((f) => f !== SW_FILE).sort();
}

/** Cache name from the paths and contents of `files` under `dir`. */
export function cacheName(dir, files) {
  const h = createHash('sha256');
  for (const f of files) {
    h.update(f);
    h.update('\0');
    h.update(readFileSync(join(dir, f)));
    h.update('\0');
  }
  return CACHE_PREFIX + h.digest('hex').slice(0, 16);
}

/** The worker's source for a cache name and a file list. */
export function swSource(name, files) {
  return `// Generated by scripts/make-sw.mjs. Do not edit.
const CACHE = ${JSON.stringify(name)};
const PREFIX = ${JSON.stringify(CACHE_PREFIX)};
const FILES = ${JSON.stringify(files, null, 0)};
const INDEX = new URL('index.html', self.registration.scope).href;

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(FILES)));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith(PREFIX) && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('message', (event) => {
  if (event.data === 'skipWaiting') self.skipWaiting();
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  if (req.mode === 'navigate') {
    event.respondWith(
      caches
        .open(CACHE)
        .then((cache) => cache.match(INDEX, { ignoreVary: true }))
        .then((hit) => hit || fetch(req))
        .catch(() => fetch(req)),
    );
    return;
  }
  event.respondWith(
    caches
      .open(CACHE)
      // Hosts often send Vary: Origin, and module scripts carry an Origin header the precache
      // requests did not: match on the URL alone.
      .then((cache) => cache.match(req, { ignoreVary: true }))
      .then((hit) => hit || fetch(req)),
  );
});
`;
}

/** Build the worker for a dist directory. Returns { name, files, source }. */
export function buildServiceWorker(dir) {
  const files = listFiles(dir);
  if (!files.includes('index.html')) throw new Error(`no index.html in ${dir}: run vite build first`);
  const name = cacheName(dir, files);
  return { name, files, source: swSource(name, files) };
}

/** Build and write `dir`/sw.js. */
export function writeServiceWorker(dir) {
  const sw = buildServiceWorker(dir);
  writeFileSync(join(dir, SW_FILE), sw.source);
  return sw;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const dir = resolve(process.argv[2] ?? join(ROOT, 'dist'));
  const sw = writeServiceWorker(dir);
  console.log(`[sw] ${sw.name}: ${sw.files.length} files precached -> ${join(dir, SW_FILE)}`);
}
